"""
Machine-readable triage outputs, generated by code from verified data:

- STIX 2.1 bundle (indicators, attack-patterns, vulnerabilities, a report)
  for MISP / OpenCTI / TAXII ingestion;
- Sigma rules (DNS, proxy, firewall, file-hash) the SOC can convert to its
  SIEM's query language;
- an ATT&CK Navigator layer to see the advisory's techniques on the matrix.

Nothing here is written by the LLM. Identifiers are deterministic (UUIDv5
of the content), so triaging the same advisory twice yields the same
objects and a SIEM can de-duplicate on id.
"""
from __future__ import annotations

import ipaddress
import json
import uuid
from datetime import datetime, timezone
from typing import Dict, List, Optional

from .enrich import attack_catalogue, catalogue_versions, lookup_kev

_NS = uuid.UUID("6f1c0e3a-5b0e-4b47-9a62-0f0b7f1e3024")  # Fortis namespace
_IDENTITY_ID = f"identity--{uuid.uuid5(_NS, 'fortis-triage-agent')}"

_STIX_PATTERN = {
    "ipv4": "ipv4-addr:value", "ipv6": "ipv6-addr:value", "domain": "domain-name:value",
    "url": "url:value", "email": "email-addr:value",
    "md5": "file:hashes.MD5", "sha1": "file:hashes.'SHA-1'", "sha256": "file:hashes.'SHA-256'",
}


def _id(kind: str, key: str) -> str:
    return f"{kind}--{uuid.uuid5(_NS, kind + ':' + key)}"


def _ts(now: Optional[datetime] = None) -> str:
    return (now or datetime.now(timezone.utc)).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def _esc(v: str) -> str:
    return v.replace("\\", "\\\\").replace("'", "\\'")


def stix_bundle(title: str, iocs: List[Dict], techniques: List[str], cves: List[str],
                summary: str = "", now: Optional[datetime] = None) -> Dict:
    ts = _ts(now)
    objs: List[Dict] = [{
        "type": "identity", "spec_version": "2.1", "id": _IDENTITY_ID, "created": ts, "modified": ts,
        "name": "Fortis triage agent", "identity_class": "system",
    }]
    refs = []
    for i in iocs:
        path = _STIX_PATTERN.get(i["type"])
        if not path:
            continue
        oid = _id("indicator", f"{i['type']}:{i['value']}")
        objs.append({
            "type": "indicator", "spec_version": "2.1", "id": oid, "created": ts, "modified": ts,
            "created_by_ref": _IDENTITY_ID, "name": f"{i['type']} {i['value']}",
            "indicator_types": ["malicious-activity"], "pattern_type": "stix",
            "pattern": f"[{path} = '{_esc(i['value'])}']", "valid_from": ts,
            "labels": ["fortis-triage"] + (["private-or-reserved-address"] if "private/reserved" in i.get("notes", []) else []),
        })
        refs.append(oid)
    cat = attack_catalogue()["techniques"]
    for t in techniques:
        if t not in cat:
            continue
        oid = _id("attack-pattern", t)
        objs.append({
            "type": "attack-pattern", "spec_version": "2.1", "id": oid, "created": ts, "modified": ts,
            "created_by_ref": _IDENTITY_ID, "name": cat[t]["name"],
            "external_references": [{"source_name": "mitre-attack", "external_id": t, "url": cat[t]["url"]}],
        })
        refs.append(oid)
    for c in cves:
        oid = _id("vulnerability", c)
        k = lookup_kev(c)
        v = {"type": "vulnerability", "spec_version": "2.1", "id": oid, "created": ts, "modified": ts,
             "created_by_ref": _IDENTITY_ID, "name": c,
             "external_references": [{"source_name": "cve", "external_id": c}]}
        if k:
            v["description"] = f"{k['vendor']} {k['product']}: {k['name']} (CISA KEV since {k['date_added']})"
        objs.append(v)
        refs.append(oid)
    # No indicator->technique relationships: the advisory rarely says which
    # indicator belongs to which step, so the report object groups them.
    objs.append({
        "type": "report", "spec_version": "2.1", "id": _id("report", title), "created": ts, "modified": ts,
        "created_by_ref": _IDENTITY_ID, "name": title, "published": ts, "report_types": ["threat-report"],
        "description": summary[:2000] or title, "object_refs": refs or [_IDENTITY_ID],
    })
    return {"type": "bundle", "id": _id("bundle", title + ts), "objects": objs}


