def navigator_layer(title: str, techniques: List[str], evidence: Dict[str, str] = None) -> Dict:
    cat = attack_catalogue()["techniques"]
    evidence = evidence or {}
    entries = []
    for t in techniques:
        if t not in cat:
            continue
        for tactic in cat[t]["tactics"] or [None]:
            e = {"techniqueID": t, "score": 1, "color": "#e0574f", "enabled": True,
                 "comment": evidence.get(t, "named in advisory")[:300]}
            if tactic:
                e["tactic"] = tactic
            entries.append(e)
    return {
        "name": title[:80], "versions": {"attack": catalogue_versions()["attack"], "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack", "description": "Generated by the Fortis triage agent from verified technique ids.",
        "techniques": entries, "gradient": {"colors": ["#ffffff", "#e0574f"], "minValue": 0, "maxValue": 1},
        "legendItems": [{"label": "Seen in advisory", "color": "#e0574f"}],
        "hideDisabled": False, "selectTechniquesAcrossTactics": True,
    }


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False)
